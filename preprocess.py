"""Очистка и нормализация текста.

Здесь убирается «мусор»: пунктуация, эмодзи, лишние пробелы, служебные
слова (стоп-слова), а кириллица транслитерируется в латиницу, чтобы
запрос «вешь» находил товар «Super vesh 3000».
"""

from __future__ import annotations

import re

__all__ = ["clean_text", "transliterate"]

# --- Транслитерация кириллицы -> латиница -------------------------------
_CYR2LAT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "c", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def transliterate(text: str) -> str:
    """Кириллица -> латиница. Латиница и цифры не меняются."""
    return "".join(_CYR2LAT.get(ch, ch) for ch in text)


# --- Стоп-слова (мусор в запросе) ---------------------------------------
_STOPWORDS_RAW = frozenset(
    {
        # служебные слова
        "и", "в", "во", "на", "по", "с", "со", "у", "к", "ко", "для",
        "за", "из", "от", "до", "под", "над", "о", "об", "обо", "при",
        "про", "через", "между", "а", "но", "или", "да", "же", "бы", "ли",
        "не", "ни", "то", "это", "этот", "эта", "эти", "вот", "так",
        "как", "чтобы", "если", "ни", "бы", "был", "быть", "есть",
        # «хочу купить ...» и прочая мольба о покупке
        "хочу", "хочется", "хочеться", "купить", "куплю", "купил", "купить",
        "брать", "беру", "взять", "возьму", "нужен", "нужна", "нужно",
        "нужны", "требуется", "ищу", "искаю", "подбери", "подберите",
        "покажи", "покажите", "дай", "дайте", "мне", "я", "мы", "мой",
        "моя", "моё", "мое", "свой", "своя", "пожалуйста", "пожалуйста",
        "где", "какой", "какая", "какие", "как-то", "можно", "можно-ли",
        "ли", "имеется", "имеются", "в", "наличие", "наличии", "заказать",
        "оформить", "стоит", "цена", "сколько", "продать", "продажа",
        # типовые слова-заполнители
        "товар", "товары", "штука", "вещь", "вещи", "item", "the", "a",
        "an", "to", "for", "and", "of", "in", "on", "is", "with",
    }
)

# Стоп-слова + их латинские транслитерации (пользователь может печатать
# транслитом: «hochu kupit vesh»).
_STOPWORDS = _STOPWORDS_RAW | {transliterate(w) for w in _STOPWORDS_RAW}

# Всё, что не буква и не цифра -> пробел (пунктуация, эмодзи, скобки...)
_NON_WORD_RE = re.compile(r"[^0-9a-zA-Zа-яА-ЯёЁ]+")


def clean_text(text: str) -> str:
    """Полная очистка текста -> строка в «каноническом» виде.

    Шаги:
      1. нижний регистр, неразрывные пробелы -> обычные пробелы;
      2. удаление всего, кроме букв/цифр (пунктуация, эмодзи, скобки);
      3. разбиение на слова и удаление стоп-слов;
      4. удаление однобуквенных «шумов»;
      5. транслитерация кириллицы в латиницу;
      6. схлопывание пробелов.
    """
    text = text.lower().replace("\u00a0", " ").replace("\u200b", "")
    text = _NON_WORD_RE.sub(" ", text)

    kept: list[str] = []
    for token in text.split():
        latin = transliterate(token)
        if token in _STOPWORDS or latin in _STOPWORDS:
            continue
        if len(token) == 1 and not token.isdigit():
            continue  # одиночные буквы-мусор
        kept.append(latin)

    return " ".join(kept)
